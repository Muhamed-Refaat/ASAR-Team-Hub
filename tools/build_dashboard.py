"""Generate both standalone dashboards and the GAS server from shared sources."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHEETS = {'supervisor': 'Supervisor', 'team': 'Team', 'skills': 'Skill', 'learning': 'Learning', 'meet': 'Meet', 'tasks': 'Task', 'logs': 'Log', 'activity': 'Activity', 'admins': 'Admins', 'skillEvents': 'SkillEvents', 'completions': 'Completion', 'skillRequirements': 'SkillRequirements', 'subteams': 'Subteams', 'memberships': 'TeamMemberships'}

def build():
    model = (ROOT / 'web/model.js').read_text(encoding='utf-8')
    css = (ROOT / 'web/theme.css').read_text(encoding='utf-8')
    app = (ROOT / 'web/app.jsx').read_text(encoding='utf-8')
    cv = (ROOT / 'web/cv.js').read_text(encoding='utf-8')
    adapter = (ROOT / 'web/local.js').read_text(encoding='utf-8')
    base = (ROOT / 'web/shell.html').read_text(encoding='utf-8')
    csvs = {key: (ROOT / f'spreedsheet-copy/{sheet}.csv').read_text(encoding='utf-8') if (ROOT / f'spreedsheet-copy/{sheet}.csv').exists() else '' for key,sheet in SHEETS.items()}
    data = json.dumps({'sheets': SHEETS, 'csv': csvs}, ensure_ascii=True).replace('</', '<\\/')
    for name, local in [('Index.html', False), ('local_test_dashboard.html', True)]:
        page = base.replace('/* MODEL */', model).replace('/* CV */', cv).replace('/* THEME */', css).replace('/* APP */', app)
        page = page.replace('/* ADAPTER */', f'const LOCAL_SEED = {data};\n{adapter}' if local else '')
        (ROOT / name).write_text('<!-- Generated by sync_local_db.py / tools/build_dashboard.py. Edit web/ sources. -->\n' + page, encoding='utf-8')
    (ROOT / 'Code.gs').write_text('// Generated from web/model.js and web/backend.gs.\n' + model + '\n' + (ROOT / 'web/backend.gs').read_text(encoding='utf-8'), encoding='utf-8')
    print('Built Index.html, local_test_dashboard.html and Code.gs from shared sources.')

if __name__ == '__main__':
    build()
